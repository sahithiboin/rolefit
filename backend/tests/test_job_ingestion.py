@pytest.mark.parametrize("failure_stage", ["initialization", "write"])
def test_storage_failure_has_safe_error(client, payload, dependencies, failure_stage):
    _, database = dependencies
    failure = RuntimeError("private credential details")
    if failure_stage == "initialization":
        database.side_effect = failure
    else:
        database.return_value.collection.return_value.document.return_value.create.side_effect = failure
    response = client.post("/api/jobs/ingest", json=payload)
    assert response.status_code == 503
    assert response.json() == {"detail": "Could not save the generated job."}


