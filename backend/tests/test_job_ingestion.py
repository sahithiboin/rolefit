@pytest.mark.parametrize("backend_project,frontend_project,expected", [
    ("runtime-project", "frontend-project", "runtime-project"),
    (None, "frontend-project", "frontend-project"),
    (None, None, None),
])
def test_firestore_project_selection(monkeypatch, backend_project, frontend_project, expected):
    for key, value in (("FIRESTORE_PROJECT_ID", backend_project),
                       ("VITE_FIREBASE_PROJECT_ID", frontend_project)):
        if value is None:
            monkeypatch.delenv(key, raising=False)
        else:
            monkeypatch.setenv(key, value)
    factory = MagicMock()
    monkeypatch.setattr(job_ingestion.firestore, "Client", factory)
    job_ingestion.get_firestore_client.cache_clear()
    try:
        job_ingestion.get_firestore_client()
        factory.assert_called_once_with(project=expected)
    finally:
        job_ingestion.get_firestore_client.cache_clear()
