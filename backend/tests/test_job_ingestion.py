@pytest.mark.parametrize("score", [1.0, 8.9, 8.999999])
def test_below_threshold_never_opens_firestore(client, payload, dependencies, score):
    generate, database = dependencies
    # Filtering must happen before even checking for a package.
    generate.return_value = {"match_analysis": {"overall_fit_score": score}}
    response = client.post("/api/jobs/ingest", json=payload)
    assert response.status_code == 200
    assert response.json() == {
        "success": False, "reason": "Match score below 9/10 threshold", "matchScore": score,
    }
    database.assert_not_called()


@pytest.mark.parametrize("score", [9.0, 9.7, 10])
def test_qualifying_job_persists_exact_schema(client, payload, dependencies, score):
    generate, database = dependencies
    generate.return_value["match_analysis"]["overall_fit_score"] = score
    response = client.post("/api/jobs/ingest", json=payload)
    assert response.status_code == 200
    assert response.json() == {
        "success": True, "jobId": "new-job-id", "matchScore": score,
        "appUrl": "https://rolefit-backend-946716696276.us-central1.run.app/tracker",
    }
    generate.assert_called_once_with(
        IngestJobRequest(**payload).userProfile.model_dump(), payload["jdText"],
        thinking_level="high",
    )
    database.return_value.collection.assert_called_once_with("jobs")
    collection = database.return_value.collection.return_value
    collection.document.assert_called_once_with()
    collection.document.return_value.create.assert_called_once_with({
        "userId": "scout-user", "title": "Engineer", "company": "Example",
        "location": "Remote", "url": "https://example.com/apply", "status": "Saved",
        "notes": "Auto-generated by RoleFit Job Scout", "source": "JobScout",
        "appliedDate": None,
        "matchAnalysis": generate.return_value["match_analysis"],
        "package": generate.return_value["results"],
        "createdAt": job_ingestion.firestore.SERVER_TIMESTAMP,
        "updatedAt": job_ingestion.firestore.SERVER_TIMESTAMP,
    })


