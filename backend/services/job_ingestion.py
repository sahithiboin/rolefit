"""Generate and persist Job Scout applications that meet the fit threshold."""

from functools import lru_cache
import math
import os

from google.cloud import firestore

from logic.generator import generate_all_in_one
from models import IngestJobRequest


APP_URL = "https://rolefit-backend-946716696276.us-central1.run.app/tracker"
MATCH_THRESHOLD = 9.0


class JobGenerationError(Exception):
    """Generation failed or returned an invalid application."""


class JobStorageError(Exception):
    """Firestore could not persist the application."""


@lru_cache(maxsize=1)
def get_firestore_client():
    """Use ADC; FIRESTORE_PROJECT_ID can select the frontend's Firebase project."""
    project_id = os.getenv("FIRESTORE_PROJECT_ID") or os.getenv("VITE_FIREBASE_PROJECT_ID")
    return firestore.Client(project=project_id or None)


def ingest_job(request: IngestJobRequest) -> dict:
    """Return a threshold rejection or the newly persisted job's ID and score."""
    try:
        generated = generate_all_in_one(
            request.userProfile.model_dump(), request.jdText, thinking_level="high"
        )
    except Exception as exc:
        raise JobGenerationError("Application generation failed.") from exc

    analysis = generated.get("match_analysis") if isinstance(generated, dict) else None
    score = analysis.get("overall_fit_score") if isinstance(analysis, dict) else None
    # Reject missing, boolean, non-finite, and out-of-scale scores rather than
    # accidentally accepting malformed model output or a score on a 0–100 scale.
    if (type(score) not in (int, float) or not math.isfinite(score)
            or not 1.0 <= score <= 10.0):
        raise JobGenerationError("Generator returned an invalid match score.")

    if score < MATCH_THRESHOLD:
        return {
            "success": False,
            "reason": "Match score below 9/10 threshold",
            "matchScore": score,
        }

    results = generated.get("results")
    if not isinstance(results, dict) or any(
        not isinstance(results.get(key), str) or not results[key].strip()
        for key in ("resume", "cover_letter", "linkedin_message")
    ):
        raise JobGenerationError("Generator returned an incomplete application package.")

    job = request.jobData
    entry = {
        "userId": request.userId,
        "title": job.title,
        "company": job.company,
        "location": job.location,
        "url": job.applyUrl,
        "status": "Saved",
        "notes": "Auto-generated by RoleFit Job Scout",
        "appliedDate": None,
        "source": "JobScout",
        "matchAnalysis": analysis,
        "package": results,
        "createdAt": firestore.SERVER_TIMESTAMP,
        "updatedAt": firestore.SERVER_TIMESTAMP,
    }
    try:
        doc_ref = get_firestore_client().collection("jobs").document()
        doc_ref.create(entry)
    except Exception as exc:
        raise JobStorageError("Could not save the generated job.") from exc

    return {"success": True, "jobId": doc_ref.id, "matchScore": score, "appUrl": APP_URL}
